from urllib.parse import unquote

from botocore.exceptions import BotoCoreError, ClientError
from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session

from app.core.database import get_db
from app.core.security import get_current_user
from app.models.meeting import Meeting
from app.models.meeting_record import MeetingRecord
from app.models.user import User
from app.schemas.uploads import (
    MultipartAbortRequest, MultipartAbortResponse, MultipartCompleteRequest,
    MultipartCompleteResponse, MultipartInitiateRequest, MultipartInitiateResponse,
    MultipartGetPresignResponse, MultipartPresignRequest, MultipartPresignResponse,
    MeetingUploadResponse,
)
from app.services import s3_multipart

router = APIRouter(prefix="/uploads/multipart", tags=["uploads"])
lookup_router = APIRouter(prefix="/uploads", tags=["uploads"])
PRESIGNED_URL_TTL_SECONDS = 900


def _authorized_meeting(db: Session, meeting_id: int, user: User) -> Meeting:
    meeting = db.query(Meeting).filter(Meeting.id == meeting_id).first()
    if meeting is None:
        raise HTTPException(status_code=404, detail="Meeting not found")
    # Current project ownership model: meeting creator owns the meeting.
    # Extend this check if meeting participants should also be allowed to upload.
    if meeting.created_by != user.id:
        raise HTTPException(status_code=403, detail="You do not have access to this meeting")
    return meeting


def _validate_key(object_key: str, user_id: int, meeting_id: int) -> None:
    # Keys are generated by the server and returned to the caller. The scope check
    # prevents a caller from operating on another user's or meeting's object.
    prefix = f"audio/{user_id}/{meeting_id}/"
    if not object_key.startswith(prefix) or len(object_key) > 1024:
        raise HTTPException(status_code=403, detail="Invalid upload object key")


@lookup_router.get("", response_model=MeetingUploadResponse)
def get_meeting_upload(
    meeting_id: int,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Return playback and generated meeting data for a completed recording."""
    _authorized_meeting(db, meeting_id, current_user)
    record = db.query(MeetingRecord).filter(MeetingRecord.meeting_id == meeting_id).first()
    if record is None:
        raise HTTPException(status_code=404, detail="Meeting recording not found")

    audio_url = None
    if record.audio_object_key:
        _validate_key(record.audio_object_key, current_user.id, meeting_id)
        try:
            audio_url = s3_multipart.generate_presigned_get_url(
                object_key=record.audio_object_key, expires_in=PRESIGNED_URL_TTL_SECONDS
            )
        except (BotoCoreError, ClientError, RuntimeError) as exc:
            raise _s3_error(exc) from exc

    return MeetingUploadResponse(
        meeting_id=meeting_id,
        audio_url=audio_url,
        summary=record.summary,
        transcript=record.transcript,
        decisions=record.decisions or [],
        action_items=record.action_items,
        task_id=record.task_id,
        status=record.status,
    )


def _s3_error(exc: Exception) -> HTTPException:
    if isinstance(exc, ClientError):
        code = exc.response.get("Error", {}).get("Code", "")
        if code in {"NoSuchUpload", "InvalidPart", "InvalidPartOrder", "EntityTooSmall"}:
            return HTTPException(status_code=400, detail="S3 rejected the multipart upload request")
    return HTTPException(status_code=502, detail="S3 request failed")


@router.post("/initiate", response_model=MultipartInitiateResponse, status_code=status.HTTP_201_CREATED)
def initiate_upload(
    payload: MultipartInitiateRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    _authorized_meeting(db, payload.meeting_id, current_user)
    key = s3_multipart.build_object_key(current_user.id, payload.meeting_id, payload.filename)
    try:
        upload_id = s3_multipart.initiate_multipart_upload(
            object_key=key, content_type=payload.content_type
        )
    except Exception as e:
        print(f"S3 INITIATE ERROR: {str(e)}")
        raise HTTPException(status_code=500, detail=f"S3 Error: {str(e)}") from e
    return MultipartInitiateResponse(meeting_id=payload.meeting_id, object_key=key, upload_id=upload_id)


@router.post("/presign", response_model=MultipartPresignResponse)
def presign_part(
    payload: MultipartPresignRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    _authorized_meeting(db, payload.meeting_id, current_user)
    _validate_key(payload.object_key, current_user.id, payload.meeting_id)
    try:
        url = s3_multipart.generate_presigned_url_for_part(
            object_key=payload.object_key, upload_id=payload.upload_id,
            part_number=payload.part_number, expires_in=PRESIGNED_URL_TTL_SECONDS,
        )
    except (BotoCoreError, ClientError, RuntimeError) as exc:
        raise _s3_error(exc) from exc
    return MultipartPresignResponse(url=url, partNumber=payload.part_number,
                                    expires_in=PRESIGNED_URL_TTL_SECONDS)


@router.get("/presign-get", response_model=MultipartGetPresignResponse)
def presign_get(
    meeting_id: int,
    object_key: str,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Return a temporary read URL for an audio object belonging to this meeting."""
    object_key = unquote(object_key)
    _authorized_meeting(db, meeting_id, current_user)
    _validate_key(object_key, current_user.id, meeting_id)
    try:
        url = s3_multipart.generate_presigned_get_url(
            object_key=object_key, expires_in=PRESIGNED_URL_TTL_SECONDS
        )
    except (BotoCoreError, ClientError, RuntimeError) as exc:
        raise _s3_error(exc) from exc
    return MultipartGetPresignResponse(url=url, expires_in=PRESIGNED_URL_TTL_SECONDS)


@router.post("/complete", response_model=MultipartCompleteResponse)
def complete_upload(
    payload: MultipartCompleteRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    _authorized_meeting(db, payload.meeting_id, current_user)
    _validate_key(payload.object_key, current_user.id, payload.meeting_id)
    numbers = [part.part_number for part in payload.parts]
    if len(numbers) != len(set(numbers)) or numbers != sorted(numbers):
        raise HTTPException(status_code=422, detail="Parts must have unique ascending part numbers")
    ordered_parts = [
        {"ETag": part.etag, "PartNumber": part.part_number} for part in payload.parts
    ]
    try:
        result = s3_multipart.complete_multipart_upload(
            object_key=payload.object_key, upload_id=payload.upload_id, parts=ordered_parts
        )
    except (BotoCoreError, ClientError, RuntimeError) as exc:
        raise _s3_error(exc) from exc

    record = db.query(MeetingRecord).filter(MeetingRecord.meeting_id == payload.meeting_id).first()
    if record is None:
        record = MeetingRecord(meeting_id=payload.meeting_id)
        db.add(record)
    record.audio_object_key = payload.object_key
    try:
        playback_url = s3_multipart.generate_presigned_get_url(
            object_key=payload.object_key, expires_in=PRESIGNED_URL_TTL_SECONDS
        )
    except (BotoCoreError, ClientError, RuntimeError) as exc:
        db.rollback()
        raise _s3_error(exc) from exc
    try:
        db.commit()
    except Exception as exc:
        db.rollback()
        # S3 is already complete; log/queue reconciliation in production.
        raise HTTPException(status_code=500, detail="Upload completed but recording metadata could not be saved") from exc

    return MultipartCompleteResponse(
        meeting_id=payload.meeting_id, object_key=payload.object_key,
        audio_url=playback_url,
        summary=record.summary,
        transcript=record.transcript,
        decisions=record.decisions or [],
        action_items=record.action_items,
        task_id=record.task_id,
        status=record.status,
    )


@router.post("/abort", response_model=MultipartAbortResponse)
def abort_upload(
    payload: MultipartAbortRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    _authorized_meeting(db, payload.meeting_id, current_user)
    _validate_key(payload.object_key, current_user.id, payload.meeting_id)
    try:
        s3_multipart.abort_multipart_upload(object_key=payload.object_key, upload_id=payload.upload_id)
    except (BotoCoreError, ClientError, RuntimeError) as exc:
        raise _s3_error(exc) from exc
    return MultipartAbortResponse()
